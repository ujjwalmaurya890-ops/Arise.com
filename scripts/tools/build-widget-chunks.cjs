#!/usr/bin/env node
const fs = require("fs"),
  path = require("path"),
  crypto = require("crypto"),
  vm = require("vm");
const root = path.resolve(__dirname, "../..");
const idxPath = path.join(root, "index.html");
let idx = fs.readFileSync(idxPath, "utf8");

// SCRIPTS now live in the JSON manifest block in index.html (CSP: no inline
// executable scripts). The loader (src/boot/widget-loader.js) reads it at runtime.
const manifestMatch = idx.match(
  /<script type="application\/json" id="arise-widget-manifest">([\s\S]*?)<\/script>/
);
if (!manifestMatch) throw new Error("widget manifest not found in index.html");
const manifest = JSON.parse(manifestMatch[1]);
const files = manifest.scripts;
if (files.length < 50) throw new Error("SCRIPTS parse looks wrong: " + files.length);

const srcMap = new Map();
let totalBytes = 0;
for (const f of files) {
  const src = fs.readFileSync(path.join(root, f), "utf8").replace(/\r\n/g, "\n");
  srcMap.set(f, src);
  totalBytes += Buffer.byteLength(src, "utf8");
}

function partitionWithTarget(t) {
  const gs = [];
  let c = [],
    sz = 0;
  for (const f of files) {
    const b = Buffer.byteLength(srcMap.get(f), "utf8");
    if (c.length && sz + b > t) {
      gs.push(c);
      c = [];
      sz = 0;
    }
    c.push(f);
    sz += b;
  }
  if (c.length) gs.push(c);
  return gs;
}

let TARGET = Math.min(256 * 1024, Math.ceil(totalBytes / 11.4));
let groups = partitionWithTarget(TARGET);
if (groups.length !== 12) {
  let lo = 16 * 1024,
    hi = Math.max(256 * 1024, totalBytes);
  for (let iter = 0; iter < 32 && groups.length !== 12; iter++) {
    const mid = Math.floor((lo + hi) / 2);
    const cand = partitionWithTarget(mid);
    if (cand.length > 12) lo = mid + 1;
    else if (cand.length < 12) hi = mid - 1;
    else {
      groups = cand;
      break;
    }
  }
}

const checkOnly = process.argv.includes("--check");
const outDir = path.join(root, "assets", "chunks");
if (!checkOnly) {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
}

const chunkUrls = [],
  chunkMap = {},
  chunkBodies = new Map();
groups.forEach((g, i) => {
  let body =
    "/* generated by scripts/tools/build-widget-chunks.cjs - do not edit; edit the source files and re-run */\n";
  for (const f of g) {
    const src = srcMap.get(f);
    body +=
      "\n/* ---- " +
      f +
      " ---- */\ntry{\n" +
      src +
      "\n}catch(__arise_e){setTimeout(function(){throw __arise_e})}\n";
  }
  new vm.Script(body, { filename: "chunk" + i }); // syntax gate: throws on any error
  const hash = crypto.createHash("sha1").update(body).digest("hex").slice(0, 8);
  const name = "./assets/chunks/w" + String(i + 1).padStart(2, "0") + "." + hash + ".js";
  chunkBodies.set(name, body);
  if (!checkOnly) fs.writeFileSync(path.join(root, name), body);
  chunkUrls.push(name);
  chunkMap[name] = g;
});

/* ---------------------------------------------------------------------------
   Route-scoped loading metadata (2026-11 performance pass).

   Before this, the page fetched + executed EVERY chunk right after boot, even
   though the default Dashboard only mounts widgets from the first three. That
   put ~2.8 MB of JS (12 chunks) on the startup path. The loader now keeps the
   exact same execution order but can tell:

     core        - chunks still loaded during startup (shared runtime + the
                   widgets the default Dashboard mounts);
     mountChunks - mount hook (window.__mountX) -> chunk that defines it, so a
                   route opened later can request just that chunk. The loader
                   still executes the earlier chunks first: widget files read
                   globals defined by earlier files at load time, sometimes
                   through local aliases of `window` that no static scan can
                   see, so order is kept by construction rather than inferred.

   The map is derived from the sources, so it stays correct when files move.
   The build fails loudly if a mount hook maps to a chunk that does not exist.
   ------------------------------------------------------------------------- */
const CORE_CHUNKS = 3;
const fileChunk = new Map();
chunkUrls.forEach(url => chunkMap[url].forEach(f => fileChunk.set(f, url)));
const chunkIndex = new Map(chunkUrls.map((url, i) => [url, i]));
const mountChunks = {};
for (const f of files) {
  const src = srcMap.get(f);
  const chunk = fileChunk.get(f);
  for (const m of src.matchAll(/window\.(__mount[A-Za-z0-9_]+)\s*=(?!=)/g))
    mountChunks[m[1]] = chunk;
}
const coreChunks = chunkUrls.slice(0, Math.min(CORE_CHUNKS, chunkUrls.length));
if (!Object.keys(mountChunks).length) throw new Error("no window.__mountX hooks found");
for (const hook of Object.keys(mountChunks))
  if (!chunkUrls.includes(mountChunks[hook]))
    throw new Error("mount hook " + hook + " maps to a missing chunk");

const newManifest = JSON.stringify({
  scripts: files,
  chunks: chunkUrls,
  chunkFiles: chunkMap,
  core: coreChunks,
  mountChunks
});
const nextIdx = idx.replace(
  /<script type="application\/json" id="arise-widget-manifest">[\s\S]*?<\/script>/,
  () => '<script type="application/json" id="arise-widget-manifest">' + newManifest + "</script>"
);

const swPath = path.join(root, "service-worker.js");
let sw = fs.readFileSync(swPath, "utf8");
let ext = JSON.parse(fs.readFileSync(path.join(__dirname, "sw-extended-base.json"), "utf8"));
ext = chunkUrls.concat(ext);
const nextSw = sw.replace(
  /EXTENDED_SHELL\s*=\s*\[[\s\S]*?\]/,
  () => "EXTENDED_SHELL=" + JSON.stringify(ext)
);

if (checkOnly) {
  const drift = [];
  if (nextIdx !== idx) drift.push("index.html");
  if (nextSw !== sw) drift.push("service-worker.js");
  if (drift.length) {
    console.error("Widget chunk manifest drift in: " + drift.join(", "));
    console.error("Run `npm run build:chunks` to update generated manifests.");
    process.exit(1);
  }
  console.log("Widget chunk manifests are up to date (" + chunkUrls.length + " chunks).");
  process.exit(0);
}

if (nextIdx !== idx) fs.writeFileSync(idxPath, nextIdx);
if (nextSw !== sw) fs.writeFileSync(swPath, nextSw);
console.log(
  files.length +
    " scripts -> " +
    chunkUrls.length +
    " chunks; SW extended list " +
    ext.length +
    " entries"
);
groups.forEach((g, i) => console.log(chunkUrls[i], g.length + " files"));
console.log(
  "startup chunks: " +
    coreChunks.length +
    " (" +
    Object.keys(mountChunks).length +
    " mount hooks mapped)"
);
