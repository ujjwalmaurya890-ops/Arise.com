#!/usr/bin/env node
const fs = require('fs'), path = require('path'), crypto = require('crypto'), vm = require('vm');
const root = path.resolve(__dirname, '..');
const idxPath = path.join(root, 'index.html');
let idx = fs.readFileSync(idxPath, 'utf8');

const listSrc = idx.match(/var SCRIPTS = \[([\s\S]*?)\];/)[1];
const files = [...listSrc.matchAll(/'([^']+\.js)'/g)].map(m => m[1]);
if (files.length < 50) throw new Error('SCRIPTS parse looks wrong: ' + files.length);

const srcMap = new Map();
let totalBytes = 0;
for (const f of files) {
  const src = fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n');
  srcMap.set(f, src);
  totalBytes += Buffer.byteLength(src, 'utf8');
}

function partitionWithTarget(t) {
  const gs = []; let c = [], sz = 0;
  for (const f of files) {
    const b = Buffer.byteLength(srcMap.get(f), 'utf8');
    if (c.length && sz + b > t) { gs.push(c); c = []; sz = 0; }
    c.push(f); sz += b;
  }
  if (c.length) gs.push(c);
  return gs;
}

let TARGET = Math.min(256 * 1024, Math.ceil(totalBytes / 11.4));
let groups = partitionWithTarget(TARGET);
if (groups.length !== 12) {
  let lo = 16 * 1024, hi = Math.max(256 * 1024, totalBytes);
  for (let iter = 0; iter < 32 && groups.length !== 12; iter++) {
    const mid = Math.floor((lo + hi) / 2);
    const cand = partitionWithTarget(mid);
    if (cand.length > 12) lo = mid + 1;
    else if (cand.length < 12) hi = mid - 1;
    else { groups = cand; break; }
  }
}

const outDir = path.join(root, 'assets', 'chunks');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const chunkUrls = [], chunkMap = {};
groups.forEach((g, i) => {
  let body = '/* generated by tools/build-widget-chunks.cjs - do not edit; edit the source files and re-run */\n';
  for (const f of g) {
    const src = srcMap.get(f);
    body += '\n/* ---- ' + f + ' ---- */\ntry{\n' + src + '\n}catch(__arise_e){setTimeout(function(){throw __arise_e})}\n';
  }
  new vm.Script(body, { filename: 'chunk' + i });          // syntax gate: throws on any error
  const hash = crypto.createHash('sha1').update(body).digest('hex').slice(0, 8);
  const name = './assets/chunks/w' + String(i + 1).padStart(2, '0') + '.' + hash + '.js';
  fs.writeFileSync(path.join(root, name), body);
  chunkUrls.push(name); chunkMap[name] = g;
});

const block = '/*CHUNKS:START*/\n    var CHUNKS = ' + JSON.stringify(chunkUrls, null, 6).replace(/\n\]$/, '\n    ]') +
  ';\n    var CHUNK_FILES = ' + JSON.stringify(chunkMap) + ';\n    /*CHUNKS:END*/';
if (/\/\*CHUNKS:START\*\//.test(idx)) idx = idx.replace(/\/\*CHUNKS:START\*\/[\s\S]*?\/\*CHUNKS:END\*\//, () => block);
else idx = idx.replace(/(var SCRIPTS = \[[\s\S]*?\];\n)/, (m) => m + '    ' + block + '\n');
fs.writeFileSync(idxPath, idx);

const swPath = path.join(root, 'service-worker.js');
let sw = fs.readFileSync(swPath, 'utf8');
let ext = JSON.parse(fs.readFileSync(path.join(__dirname, 'sw-extended-base.json'), 'utf8'));
ext = chunkUrls.concat(ext);
sw = sw.replace(/EXTENDED_SHELL=\[[\s\S]*?\]/, () => 'EXTENDED_SHELL=' + JSON.stringify(ext));
fs.writeFileSync(swPath, sw);
console.log(files.length + ' scripts -> ' + chunkUrls.length + ' chunks; SW extended list ' + ext.length + ' entries');
groups.forEach((g, i) => console.log(chunkUrls[i], g.length + ' files'));
